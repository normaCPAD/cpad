"""Data-quality metrics and a shareable "data health" report.

quality_metrics : conformance, current normal form, candidate keys, and a redundancy
index (the share of redundant storage the normalization removes).
build_html_report : a self-contained HTML report (constraints, schema, metrics, top
anomalies, repair summary) renderable by a browser or Qt's QTextDocument (-> PDF).
"""
from __future__ import annotations
import html

from cpad.modeling.report import _kind


def quality_metrics(table, schema, scores, threshold: float = 0.7) -> dict:
    n, d = table.n, len(table.columns)
    total = max(1, n * d)
    flagged = int((scores > threshold).sum()) if scores is not None else 0
    conformance = 1.0 - flagged / total

    rels = schema.relations_bcnf
    if rels:
        attrs = set().union(*[set(r.attributes) for r in rels])
        flat_cells = n * len(attrs)
        norm_cells = sum(len(table.df[sorted(r.attributes)].drop_duplicates()) * len(r.attributes)
                         for r in rels)
        redundancy = max(0.0, 1.0 - norm_cells / max(1, flat_cells))
    else:
        flat_cells = norm_cells = 0; redundancy = 0.0

    return {
        "rows": n, "columns": d, "flagged_cells": flagged,
        "conformance": conformance, "normal_form": schema.normal_form,
        "candidate_keys": len(schema.keys), "relations": len(rels),
        "redundancy": redundancy, "flat_cells": flat_cells, "norm_cells": norm_cells,
    }


def _e(x):
    return html.escape(str(x))


def _table(headers, rows, widths=None):
    """A QTextDocument-friendly HTML table (uses only the supported subset)."""
    out = ['<table border="1" width="100%" cellspacing="0" cellpadding="5" '
           'style="border-color:#d0d6e0;border-collapse:collapse">']
    out.append('<tr bgcolor="#eef2f8">' + "".join(
        f'<th align="left"{f" width={w}" if w else ""}>{h}</th>' for h, w in zip(headers, widths or [None] * len(headers))) + "</tr>")
    for r in rows:
        out.append("<tr>" + "".join(f'<td valign="top">{c}</td>' for c in r) + "</tr>")
    out.append("</table>")
    return "".join(out)


def _h2(title):
    return f'<br><font size="5" color="#2d7ff9"><b>{title}</b></font><hr>'


