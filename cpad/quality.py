def build_html_report(table, rules, schema, metrics, anomalies=None, repair=None, lang="fr") -> str:
    """Self-contained report using only QTextDocument-supported HTML (table layout, font
    tags, bgcolor) so it renders identically in the app and in the exported PDF. `lang`
    selects the report language ('fr' / 'en'); French uses proper accents."""
    m = metrics
    L = REPORT_LABELS.get(lang, REPORT_LABELS["fr"])
    P = ['<html><body style="font-family:Helvetica,Arial,sans-serif;color:#1a1f29">']
    P.append(f'<font size="6"><b>{_e(L["title"])}</b></font><br>')
    P.append(f'<font size="4" color="#445">{_e(table.name)} &nbsp;&middot;&nbsp; '
             f'{m["rows"]} {_e(L["rows"])} &times; {m["columns"]} {_e(L["columns"])}</font><br>')
    P.append(f'<font color="#778">{_e(L["subtitle"])}</font>')

    cards = [(L["conformance"], f"{m['conformance']*100:.1f}%"),
             (L["normal_form"], m["normal_form"]),
             (L["candidate_keys"], str(m["candidate_keys"])),
             (L["redundancy"], f"{m['redundancy']*100:.0f}%"),
             (L["flagged"], str(m["flagged_cells"]))]
    P.append(_h2(_e(L["indicators"])))
    P.append('<table width="100%" cellspacing="6" cellpadding="10"><tr>')
    for label, val in cards:
        P.append(f'<td align="center" bgcolor="#f3f7ff" width="20%">'
                 f'<font size="6" color="#2d7ff9"><b>{_e(val)}</b></font><br>'
                 f'<font size="2" color="#667">{_e(label)}</font></td>')
    P.append("</tr></table>")

    P.append(_h2(f'{_e(L["constraints"])} ({len(rules)})'))
    P.append(_table([L["type"], L["rule"], L["confidence"]],
                    [[_e(_kind(o)), _e(o), f"{getattr(o, 'confidence', 1.0):.3f}"] for o in rules],
                    widths=["18%", None, "14%"]))

    P.append(_h2(_e(L["schema"])))
    P.append(_table([L["relation"], L["attributes"], L["key"]],
                    [[_e(r.name), _e(", ".join(sorted(r.attributes))), _e(", ".join(sorted(r.key)))]
                     for r in schema.relations_bcnf], widths=["14%", None, "26%"]))

    if repair is not None and repair.n_edits:
        P.append(_h2(f'{_e(L["repair"])} ({repair.n_edits} {_e(L["cells"])})'))
        P.append(_table([L["row"], L["column"], L["before"], L["after"], L["rule"]],
                        [[str(e.row), _e(e.column), _e(e.old), f'<font color="#1b8a5a">{_e(e.new)}</font>', _e(e.rule)]
                         for e in repair.edits[:15]], widths=["8%", "16%", "16%", "16%", None]))

    if anomalies:
        P.append(_h2(_e(L["anomalies"])))
        P.append(_table([L["row"], L["column"], L["value"], L["score"]],
                        [[str(a["row"]), _e(a["column"]), _e(a["value"]), f"{a['score']:.3f}"]
                         for a in anomalies[:15]], widths=["10%", "26%", None, "14%"]))

    P.append("</body></html>")
    return "\n".join(P)
